// Copies what the website needs from the contract build:
//   src/assets/vault-artifact.js       ABI, creation bytecode and runtime bytecode of OxvaVault (window.OxvaVaultArtifact).
//                                      The runtime code lets the page check that an address really runs this contract.
//   src/assets/vendor/ethers.umd.min.js the ethers library, served from our own domain (CSP allows 'self' only)
// Run from contracts/: npm run export
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..", "..");
const art = require(path.join(__dirname, "..", "artifacts", "contracts", "OxvaVault.sol", "OxvaVault.json"));
const sol = fs.readFileSync(path.join(__dirname, "..", "contracts", "OxvaVault.sol"), "utf8");
const version = (sol.match(/VERSION = "OxvaVault ([^ "]+)/) || [])[1];
if (!version) throw new Error("VERSION not found in OxvaVault.sol");
const pkg = require(path.join(__dirname, "..", "node_modules", "ethers", "package.json"));

const out = `/* Generated by contracts/scripts/export.js from contracts/contracts/OxvaVault.sol. Do not edit by hand. */
window.OxvaVaultArtifact = ${JSON.stringify({ contractName: art.contractName, compiler: "solc 0.8.28, optimizer 200, evm paris", version, abi: art.abi, bytecode: art.bytecode, deployedBytecode: art.deployedBytecode })};
`;
fs.writeFileSync(path.join(root, "src", "assets", "vault-artifact.js"), out);
console.log("wrote src/assets/vault-artifact.js (" + out.length + " bytes, bytecode " + (art.bytecode.length - 2) / 2 + " bytes)");

const vendor = path.join(root, "src", "assets", "vendor");
fs.mkdirSync(vendor, { recursive: true });
const src = path.join(__dirname, "..", "node_modules", "ethers", "dist", "ethers.umd.min.js");
fs.copyFileSync(src, path.join(vendor, "ethers.umd.min.js"));
// replace only the ethers line, so the other bundles (walletconnect.js, three-oxva.js) stay listed
const readme = path.join(vendor, "README.md");
const others = fs.existsSync(readme) ? fs.readFileSync(readme, "utf8").split(/\r?\n/).filter((l) => l && !l.startsWith("ethers.umd.min.js")) : [];
fs.writeFileSync(readme, [`ethers.umd.min.js is ethers v${pkg.version} (MIT license), copied by contracts/scripts/export.js.`].concat(others).join("\n") + "\n");
console.log("copied ethers v" + pkg.version + " to src/assets/vendor/ (" + fs.statSync(src).size + " bytes)");
